#!/usr/bin/env python3
"""Build app/src/main/assets/foods.json — the single bundled food database.

Inputs (data/sources/):
    jp_foods.json      names/categories of 日本食品標準成分表（八訂） (MEXT)
    jp_nutrients.json  nutrient values for the same foods, keyed by foodId
    usda_foods.json    selected USDA FoodData Central foods
    tw_foods.json      Taiwan TFDA foods, generated by tools/convert_tfda.py

Steps:
    1. Normalise every source into one fixed schema (RECORD_FIELDS / NUTRIENTS below): every record
       has exactly the same top-level fields and the same nutrient columns; values a source does not
       provide are null (never a missing key).
    2. Map every source category onto one category set (CATEGORIES), the one used by the scoring code.
    3. Fix known translation collisions (different foods sharing one Chinese/English name).
    4. Fill derivable gaps (available carbohydrate, energy) and list them in "estimatedNutrients".
    5. De-duplicate foods that appear in several sources under the same Chinese name,
       keeping the first source in SOURCE_PRIORITY (Taiwan data is local and the most complete).

Usage:
    python3 tools/build_foods.py            # writes foods.json and data/build_report.md

After changing the output, bump FOOD_DATA_VERSION in FoodDbSeeder.kt so installed apps re-sync.
"""

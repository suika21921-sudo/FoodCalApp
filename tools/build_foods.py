def load(name):
    with open(os.path.join(SRC, name), encoding="utf-8") as f:
        return json.load(f)


def num(v):
    return float(v) if isinstance(v, (int, float)) else None


def unified_category(source, category_en, name_en):
    if source == "US":
        target = US_CATEGORY_MAP[category_en]
        category_en = target(name_en) if callable(target) else target
    if category_en not in CATEGORIES:
        raise ValueError(f"{source}: unmapped category {category_en!r} ({name_en})")
    zh, ja = CATEGORIES[category_en]
    return category_en, zh, ja


def record(source, fdc_id, source_code, base, values, extra=None, estimated=()):
    """Build one record with the fixed RECORD_FIELDS and the fixed NUTRIENTS columns."""
    extra = extra or {}
    name_en = (base.get("nameEn") or "").strip()
    if CJK_RE.search(name_en):          # TFDA sometimes has no English name and repeats the Chinese one
        name_en = ""
    cat_en, cat_zh, cat_ja = unified_category(source, base.get("categoryEn"), name_en)
    nutrients = OrderedDict((k, {"amount": values.get(k), "unit": unit}) for k, unit in NUTRIENTS.items())
    rec = OrderedDict([
        ("fdcId", fdc_id),
        ("source", source),
        ("sourceCode", source_code),
        ("nameEn", name_en),
        ("nameZh", (base.get("nameZh") or "").strip()),
        ("nameJa", (base.get("nameJa") or "").strip()),
        ("aliasesZh", extra.get("aliasesZh") or []),
        ("categoryEn", cat_en),
        ("categoryZh", cat_zh),
        ("categoryJa", cat_ja),
        ("description", extra.get("description") or ""),
        ("refusePercent", extra.get("refusePercent")),
        ("mergedFrom", extra.get("mergedFrom") or []),
        ("nutrients", nutrients),
        ("estimatedNutrients", [k for k in NUTRIENTS if k in estimated]),
    ])
    assert list(rec) == RECORD_FIELDS
    return rec


def load_jp():
    rows = {row["foodId"]: row for row in load("jp_nutrients.json")}
    out = []
    for base in load("jp_foods.json"):
        row = rows.get(base["fdcId"], {})
        values = {key: num(row.get(field)) for field, key in JP_FIELDS.items()}
        if values["Available carbohydrate"] is None:   # official alternative: available carb by difference
            values["Available carbohydrate"] = num(row.get("choavldf"))
        out.append(record("JP", base["fdcId"], f"{base['fdcId']:05d}", base, values,
                          {"refusePercent": num(row.get("refuse"))}))
    return out


def load_us():
    out = []
    for f in load("usda_foods.json"):
        values = {k: (v or {}).get("amount") for k, v in f.get("nutrients", {}).items()}
        estimated = {k for k, v in f.get("nutrients", {}).items() if (v or {}).get("note")}
        out.append(record("US", f["fdcId"], str(f["fdcId"]), f, values, estimated=estimated))
    return out


def load_tw():
    out = []
    for f in load("tw_foods.json"):
        values = {k: (v or {}).get("amount") for k, v in f["nutrients"].items()}
        estimated = {k for k, v in f["nutrients"].items() if (v or {}).get("note")}
        out.append(record("TW", f["fdcId"], f["sourceCode"], f, values, f, estimated))
    return out


def apply_name_fixes(foods, log):
    for f in foods:
        fix = NAME_FIXES.get((f["source"], f["fdcId"])) or NAME_FIXES.get((f["source"], f["nameEn"]))
        if fix:
            changes = [f"{k} {f[k]} → {v}" for k, v in fix.items() if f[k] != v]
            f.update(fix)
            log.append(f"- {f['source']} {f['fdcId']} ({f['nameJa'] or f['nameEn']}): " + "; ".join(changes))


def amount(f, key):
    return f["nutrients"][key]["amount"]


def set_estimate(f, key, value):
    f["nutrients"][key]["amount"] = value
    f["estimatedNutrients"] = [k for k in NUTRIENTS if k in set(f["estimatedNutrients"]) | {key}]


def fill_gaps(foods, log):
    carb_count = energy_count = 0
    for f in foods:
        carb, fib = amount(f, "Carbohydrate, by difference"), amount(f, "Fiber, total dietary")
        if amount(f, "Available carbohydrate") is None and carb is not None:
            set_estimate(f, "Available carbohydrate", round(max(carb - (fib or 0.0), 0.0), 2))
            carb_count += 1
        if amount(f, "Energy") is None:
            p, fat = amount(f, "Protein"), amount(f, "Total lipid (fat)")
            # Only when all three macros are known — treating a missing macro as 0 underestimates badly.
            if p is not None and fat is not None and carb is not None:
                set_estimate(f, "Energy", round(4 * (p or 0) + 9 * (fat or 0) + 4 * (carb or 0), 1))
                energy_count += 1
    log.append(f"- Available carbohydrate estimated as (carbohydrate by difference - fiber) for {carb_count} foods.")
    log.append(f"- Energy estimated with Atwater general factors (4/9/4 kcal/g) for {energy_count} foods "
               "(only when protein, fat and carbohydrate are all known; otherwise left null).")


def coverage(foods):
    lines = ["| Nutrient | Unit | " + " | ".join(SOURCE_PRIORITY) + " |",
             "|---|---|" + "---|" * len(SOURCE_PRIORITY)]
    by_src = defaultdict(list)
    for f in foods:
        by_src[f["source"]].append(f)
    for key, unit in NUTRIENTS.items():
        cells = []
        for s in SOURCE_PRIORITY:
            group = by_src[s]
            have = sum(1 for f in group if amount(f, key) is not None)
            cells.append(f"{have}/{len(group)}")
        lines.append(f"| {key} | {unit} | " + " | ".join(cells) + " |")
    return lines


def norm(name):
    return re.sub(r"[\s　、，,()（）\[\]<>・/:;\-]", "", name or "").lower()


def dedupe(foods, log):
    rank = {s: i for i, s in enumerate(SOURCE_PRIORITY)}
    groups = defaultdict(list)
    for f in foods:
        groups[norm(f["nameZh"])].append(f)
    keep_ids = set()
    for key, group in groups.items():
        sources = {f["source"] for f in group}
        if len(sources) == 1:
            keep_ids.update(id(f) for f in group)
            continue
        best = min(rank[f["source"]] for f in group)
        winners = [f for f in group if rank[f["source"]] == best]
        keep_ids.update(id(f) for f in winners)
        dropped = [f for f in group if rank[f["source"]] != best]
        log.append(f"- {winners[0]['nameZh']}: kept {best_label(winners)}, dropped "
                   + ", ".join(f"{f['source']} {f['fdcId']} ({f['nameEn']})" for f in dropped))
    return [f for f in foods if id(f) in keep_ids]


def best_label(winners):
    return ", ".join(f"{f['source']} {f['fdcId']}" for f in winners)


def main():
    fixes, energy, dupes = [], [], []
    foods = load_jp() + load_us() + load_tw()
    total_in = Counter(f["source"] for f in foods)

    apply_name_fixes(foods, fixes)
    fill_gaps(foods, energy)
    foods = dedupe(foods, dupes)

    ids = [f["fdcId"] for f in foods]
    assert len(ids) == len(set(ids)), "duplicate fdcId"
    remaining = Counter(norm(f["nameZh"]) for f in foods)
    same_name = [k for k, v in remaining.items() if v > 1]
    assert not same_name, f"duplicate Chinese names remain: {same_name[:10]}"
    for f in foods:   # schema check: identical fields and nutrient columns everywhere
        assert list(f) == RECORD_FIELDS and list(f["nutrients"]) == list(NUTRIENTS), f["fdcId"]

    with open(OUT, "w", encoding="utf-8") as fp:
        json.dump(foods, fp, ensure_ascii=False, separators=(",", ":"))

    total_out = Counter(f["source"] for f in foods)
    lines = ["# foods.json build report", "",
             "Generated by `tools/build_foods.py`.", "",
             "| Source | Input | Output |", "|---|---|---|"]
    for s in SOURCE_PRIORITY:
        lines.append(f"| {s} | {total_in[s]} | {total_out[s]} |")
    lines += [f"| **Total** | {sum(total_in.values())} | {len(foods)} |", "",
              "## Renamed (translation collisions)", *fixes, "",
              "## Schema",
              f"Every record has the same {len(RECORD_FIELDS)} fields: " + ", ".join(f"`{k}`" for k in RECORD_FIELDS) + ".",
              f"`nutrients` always has the same {len(NUTRIENTS)} columns (per 100 g); `amount` is null when the source has no value.", "",
              "## Coverage (non-null values / foods)", *coverage(foods), "",
              "## Estimated values", *energy, "",
              "## Incomplete records (energy unknown)",
              *[f"- {f['source']} {f['fdcId']} {f['nameEn'] or f['nameZh']}" for f in foods if amount(f, "Energy") is None], "",
              f"## Cross-source duplicates removed (priority {' > '.join(SOURCE_PRIORITY)})", *dupes, ""]
    with open(REPORT, "w", encoding="utf-8") as fp:
        fp.write("\n".join(lines))
    print(f"foods.json: {len(foods)} foods {dict(total_out)} ({os.path.getsize(OUT)//1024} KB); report -> {REPORT}")


if __name__ == "__main__":
    sys.exit(main())

REPORT = os.path.join(ROOT, "data", "build_report.md")

SOURCE_PRIORITY = ["TW", "JP", "US"]

# Fixed top-level fields of every record, in output order.
RECORD_FIELDS = [
    "fdcId", "source", "sourceCode",
    "nameEn", "nameZh", "nameJa", "aliasesZh",
    "categoryEn", "categoryZh", "categoryJa",
    "description", "refusePercent", "mergedFrom",
    "nutrients", "estimatedNutrients",
]

# Fixed nutrient columns (key -> unit, per 100 g edible portion). The first 8 are
